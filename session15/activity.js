// Mini-Activity1
let celcius = prompt("Enter the temperature in Celcius: ");
let kelvin = parseInt(celcius) + 273.15;
alert("The temperature in Kelvin is: " + kelvin);

// Mini-Activity2
let pi = 3.14159;
let radius = prompt("Enter the radius of the circle: ");
let area = pi * (parseInt(radius) * parseInt(radius));
alert("The area of the circle is: " + area);